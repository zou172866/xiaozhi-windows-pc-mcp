$ErrorActionPreference = "Continue"
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

$serverDir = Split-Path -Parent $PSScriptRoot
Set-Location $serverDir

Write-Host "=========================================================" -ForegroundColor Cyan
Write-Host "  小智 ESP32 · 跨电脑开箱即用 一键初始化向导" -ForegroundColor Cyan
Write-Host "=========================================================" -ForegroundColor Cyan

# 1. 自动探测局域网 IPv4
$detectedIp = ""
try {
    $detectedIp = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
        Where-Object {
            $_.IPAddress -notlike "127.*" -and
            $_.IPAddress -notlike "169.254.*" -and
            $_.InterfaceAlias -notmatch "WSL|vEthernet|Docker|Loopback|Hyper-V|VirtualBox|VMware"
        } |
        Sort-Object -Property InterfaceMetric |
        Select-Object -First 1 -ExpandProperty IPAddress
} catch {}
if (-not $detectedIp) { $detectedIp = "192.168.1.100" }

$ipIn = Read-Host "`n[1/5] 本机局域网 IP（直接回车使用自动探测值 $detectedIp）"
$hostLanIp = if ($ipIn.Trim()) { $ipIn.Trim() } else { $detectedIp }

# 2. 选择 L3 后台 Agent 后端
Write-Host "`n[2/5] 请选择 L3 复杂任务后台 Agent 引擎（日后可在 18080 控制台随时免重启切换）：" -ForegroundColor Yellow
Write-Host "  1) DeepSeek DSH (@deepseek-ai/dsh，国内直连，推荐)"
Write-Host "  2) 腾讯 WorkBuddy / CodeBuddy CLI (workbuddy / codebuddy / cbc，国内直连)"
Write-Host "  3) Google Antigravity（反重力客户端 Sidecar 桥接）"
Write-Host "  4) 暂不启用 L3（仅使用 L1 系统控制 + L2 视觉键鼠）"
$l3Choice = (Read-Host "请输入编号 [1-4，默认 1]").Trim()
switch ($l3Choice) {
    "2" { $l3Backend = "workbuddy" }
    "3" { $l3Backend = "antigravity" }
    "4" { $l3Backend = "none" }
    default { $l3Backend = "dsh" }
}

$defaultWorkdir = Split-Path -Parent $serverDir
$wdIn = Read-Host "L3 后台任务默认工作目录（直接回车使用 $defaultWorkdir）"
$l3Workdir = if ($wdIn.Trim()) { $wdIn.Trim() } else { $defaultWorkdir }

# 3. 选择语音合成方案
Write-Host "`n[3/5] 请选择语音合成（TTS）方案：" -ForegroundColor Yellow
Write-Host "  1) 免显卡 EdgeTTS（推荐无独显/轻薄本，零显存占用开箱即用）"
Write-Host "  2) 本地 RTX GPU GPT-SoVITS（需单独部署 gpt-sovits-studio）"
$ttsChoice = (Read-Host "请输入编号 [1-2，默认 1]").Trim()
$enableGsv = if ($ttsChoice -eq "2") { "true" } else { "false" }
$gsvDir = ""
if ($enableGsv -eq "true") {
    $candGsv = Join-Path (Split-Path -Parent $serverDir) "gpt-sovits-studio"
    $gsvIn = Read-Host "本地 gpt-sovits-studio 目录（直接回车使用 $candGsv）"
    $gsvDir = if ($gsvIn.Trim()) { $gsvIn.Trim() } else { $candGsv }
}

# 4. 选择长期记忆模型网络
Write-Host "`n[4/5] 请选择 Anima Brain 长期记忆模型网络：" -ForegroundColor Yellow
Write-Host "  1) 纯国内免梯子（DeepSeek 对话摘要 + 可选硅基流动/百炼 Embedding）"
Write-Host "  2) Google Gemini（需代理/全局 TUN 与 GEMINI_API_KEY）"
$memChoice = (Read-Host "请输入编号 [1-2，默认 1]").Trim()

$envLines = @(
    "# Generated by init_setup.ps1 ($(Get-Date -Format 'yyyy-MM-dd HH:mm:ss'))",
    "HOST_LAN_IP=$hostLanIp",
    "L3_BACKEND=$l3Backend",
    "XIAOZHI_L3_WORKDIR=$l3Workdir",
    "ENABLE_LOCAL_GSV=$enableGsv"
)
if ($gsvDir) { $envLines += "GSV_DIR=$gsvDir" }

if ($memChoice -eq "2") {
    $envLines += @(
        "ANIMA_LLM_BASE_URL=https://generativelanguage.googleapis.com/v1beta/openai",
        "ANIMA_LLM_MODEL=gemini-3.5-flash-lite",
        "ANIMA_EMBEDDING_BASE_URL=https://generativelanguage.googleapis.com/v1beta/openai",
        "ANIMA_EMBEDDING_MODEL=gemini-embedding-001"
    )
} else {
    $envLines += @(
        "ANIMA_LLM_BASE_URL=https://api.deepseek.com/v1",
        "ANIMA_LLM_MODEL=deepseek-chat",
        "# 若需要长期语义向量检索，可填入国内兼容 Embedding 地址并把 Key 存入系统环境变量 ANIMA_EMBEDDING_API_KEY",
        "ANIMA_EMBEDDING_BASE_URL=",
        "ANIMA_EMBEDDING_MODEL=",
        "ANIMA_EMBEDDING_API_KEY="
    )
}

$dotEnvPath = Join-Path $serverDir ".env"
[System.IO.File]::WriteAllLines($dotEnvPath, $envLines, [System.Text.UTF8Encoding]::new($false))
Write-Host "`n[已生成] 本地环境文件: $dotEnvPath" -ForegroundColor Green

# 写入 data/l3_backend_config.json
$l3CfgPath = Join-Path $serverDir "data\l3_backend_config.json"
$l3Json = @{
    backend = $l3Backend
    workdir = $l3Workdir
    dsh_cmd = ""
    workbuddy_cmd = ""
    workbuddy_auto_approve = $true
    timeout_seconds = 300
} | ConvertTo-Json -Depth 4
[System.IO.File]::WriteAllText($l3CfgPath, $l3Json, [System.Text.UTF8Encoding]::new($false))
Write-Host "[已生成] L3 引擎配置:  $l3CfgPath" -ForegroundColor Green

# 按需从 .example 模板生成缺失的运行态配置文件（绝不覆盖已有个人设定）
$runtimeTemplates = @(
    @{ Tpl = "data\.config.example.yaml";           Dst = "data\.config.yaml";           Label = "默认小智主配置" },
    @{ Tpl = "data\pc_control_mode.example.json";   Dst = "data\pc_control_mode.json";   Label = "电脑操控权限挡位" },
    @{ Tpl = "data\audio_output_mode.example.json"; Dst = "data\audio_output_mode.json"; Label = "语音播报输出端配置" },
    @{ Tpl = "data\reply_length_config.example.json"; Dst = "data\reply_length_config.json"; Label = "回复字数控制配置" },
    @{ Tpl = "data\tts_infer_xiaozhi.example.yaml"; Dst = "data\tts_infer_xiaozhi.yaml"; Label = "GPT-SoVITS 推理配置" },
    @{ Tpl = "data\.wakeup_words.example.yaml";     Dst = "data\.wakeup_words.yaml";     Label = "唤醒词缓存索引" }
)
foreach ($item in $runtimeTemplates) {
    $tplFull = Join-Path $serverDir $item.Tpl
    $dstFull = Join-Path $serverDir $item.Dst
    if (-not (Test-Path $dstFull) -and (Test-Path $tplFull)) {
        Copy-Item $tplFull $dstFull
        Write-Host "[已生成] $($item.Label): $($item.Dst)" -ForegroundColor Green
    }
}

# 若用户选择免显卡 EdgeTTS，同步确保 data\.config.yaml 的 selected_module.TTS 为 EdgeTTS（不改动其余个人设定）
$cfgPath = Join-Path $serverDir "data\.config.yaml"
if ($enableGsv -eq "false" -and (Test-Path $cfgPath)) {
    $cfgRaw = [System.IO.File]::ReadAllText($cfgPath, [System.Text.Encoding]::UTF8)
    $ttsPat = '(?m)^(\s*TTS:\s*)["'']?GPT_SOVITS_V2["'']?(\s*(?:#.*)?\r?)$'
    if ($cfgRaw -match $ttsPat) {
        $cfgUpdated = [regex]::Replace($cfgRaw, $ttsPat, '${1}EdgeTTS${2}')
        [System.IO.File]::WriteAllText($cfgPath, $cfgUpdated, [System.Text.UTF8Encoding]::new($false))
        Write-Host "[已同步] data\.config.yaml 中 TTS 已设为 EdgeTTS（免显卡模式）" -ForegroundColor Green
    }
}

# 5. 检查 Python 虚拟环境与 API Key 环境变量
Write-Host "`n[5/5] 正在检查宿主机运行依赖与环境变量..." -ForegroundColor Cyan
$venvPy = Join-Path $serverDir "pc-mcp\.venv\Scripts\python.exe"
if (-not (Test-Path $venvPy)) {
    $mk = (Read-Host "未检测到 pc-mcp\.venv 虚拟环境，是否立即自动创建并安装依赖？[Y/n]").Trim().ToLower()
    if ($mk -ne "n") {
        python -m venv (Join-Path $serverDir "pc-mcp\.venv")
        & (Join-Path $serverDir "pc-mcp\.venv\Scripts\pip.exe") install -r (Join-Path $serverDir "pc-mcp\requirements.txt")
    }
} else {
    Write-Host "  [OK] pc-mcp\.venv 已就绪" -ForegroundColor Green
}

$dsKey = [Environment]::GetEnvironmentVariable("DEEPSEEK_API_KEY", "User")
if (-not $dsKey) { $dsKey = [Environment]::GetEnvironmentVariable("DEEPSEEK_API_KEY", "Machine") }
if (-not $dsKey) {
    Write-Host "  [提示] 尚未检测到 DEEPSEEK_API_KEY 环境变量。" -ForegroundColor Yellow
    $inputKey = (Read-Host "可直接粘贴 DeepSeek API Key 写入当前 Windows 用户环境变量（留空跳过）").Trim()
    if ($inputKey) {
        $dsKey = $inputKey
        [Environment]::SetEnvironmentVariable("DEEPSEEK_API_KEY", $inputKey, "User")
        Write-Host "  [OK] 已安全写入 DEEPSEEK_API_KEY 到 Windows 用户环境变量（零明文落盘）" -ForegroundColor Green
    }
} else {
    Write-Host "  [OK] DEEPSEEK_API_KEY 环境变量已配置" -ForegroundColor Green
}

if ($memChoice -eq "2") {
    # 切换至 Google Gemini 时清理可能残留的旧 ANIMA_LLM_API_KEY（避免把 DeepSeek Key 误发给 Gemini）
    $oldAnimaKey = [Environment]::GetEnvironmentVariable("ANIMA_LLM_API_KEY", "User")
    if ($oldAnimaKey) {
        [Environment]::SetEnvironmentVariable("ANIMA_LLM_API_KEY", $null, "User")
        Write-Host "  [已清理] 已移除旧的 ANIMA_LLM_API_KEY 用户环境变量，记忆大脑将使用 GEMINI_API_KEY" -ForegroundColor Yellow
    }
    [Environment]::SetEnvironmentVariable("ANIMA_LLM_API_KEY", $null, "Process")
    $machineAnimaKey = [Environment]::GetEnvironmentVariable("ANIMA_LLM_API_KEY", "Machine")
    if ($machineAnimaKey) {
        Write-Host "  [注意] 检测到系统级 (Machine) 环境变量 ANIMA_LLM_API_KEY，请在系统环境变量中手动删除以免覆盖 GEMINI_API_KEY" -ForegroundColor Yellow
    }
    $gemKey = [Environment]::GetEnvironmentVariable("GEMINI_API_KEY", "User")
    if (-not $gemKey) { $gemKey = [Environment]::GetEnvironmentVariable("GEMINI_API_KEY", "Machine") }
    if (-not $gemKey) {
        Write-Host "  [提示] 尚未检测到 GEMINI_API_KEY 环境变量。" -ForegroundColor Yellow
        $inputGem = (Read-Host "可直接粘贴 Google Gemini API Key 写入当前 Windows 用户环境变量（留空跳过）").Trim()
        if ($inputGem) {
            [Environment]::SetEnvironmentVariable("GEMINI_API_KEY", $inputGem, "User")
            [Environment]::SetEnvironmentVariable("GEMINI_API_KEY", $inputGem, "Process")
            Write-Host "  [OK] 已安全写入 GEMINI_API_KEY 到 Windows 用户环境变量（零明文落盘）" -ForegroundColor Green
        }
    } else {
        Write-Host "  [OK] GEMINI_API_KEY 环境变量已配置" -ForegroundColor Green
    }
} else {
    if ($dsKey) {
        [Environment]::SetEnvironmentVariable("ANIMA_LLM_API_KEY", $dsKey, "User")
        [Environment]::SetEnvironmentVariable("ANIMA_LLM_API_KEY", $dsKey, "Process")
        Write-Host "  [OK] 已将 ANIMA_LLM_API_KEY 同步为当前 DEEPSEEK_API_KEY（纯国内免梯子模式）" -ForegroundColor Green
    }
}

$sherpaModel = Join-Path $serverDir "models\sherpa-onnx-sense-voice\model.int8.onnx"
if (-not (Test-Path $sherpaModel)) {
    Write-Host "  [提示] 尚未放入本地语音识别模型 models\sherpa-onnx-sense-voice\model.int8.onnx（首次启动时容器会自动按需下载或可手动放入）" -ForegroundColor Yellow
} else {
    Write-Host "  [OK] Sherpa-ONNX 离线语音识别模型已就位" -ForegroundColor Green
}

Write-Host "`n=========================================================" -ForegroundColor Green
Write-Host "初始化完成！接下来请直接双击「启动或重启服务.bat」启动全部服务。" -ForegroundColor Green
Write-Host "ESP32 OTA 烧录地址: http://${hostLanIp}:18003/xiaozhi/ota/" -ForegroundColor White
Write-Host "Web 主控制台:       http://localhost:18080" -ForegroundColor White
Write-Host "=========================================================" -ForegroundColor Green
