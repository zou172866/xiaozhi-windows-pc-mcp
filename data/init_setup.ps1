function Read-DotEnvMap {
    param([string]$Path)
    $map = @{}
    if (-not (Test-Path $Path)) { return $map }
    foreach ($rawLine in [System.IO.File]::ReadAllLines($Path, [System.Text.Encoding]::UTF8)) {
        $line = $rawLine.TrimStart([char]0xfeff).Trim()
        if (-not $line -or $line.StartsWith("#")) { continue }
        $idx = $line.IndexOf("=")
        if ($idx -le 0) { continue }
        $k = $line.Substring(0, $idx).Trim()
        $v = $line.Substring($idx + 1).Trim().Trim('"').Trim("'")
        if ($k) { $map[$k] = $v }
    }
    return $map
}

function Merge-DotEnvFile {
    param(
        [string]$Path,
        [System.Collections.Specialized.OrderedDictionary]$Updates
    )
    $existingLines = @()
    if (Test-Path $Path) {
        $existingLines = [System.IO.File]::ReadAllLines($Path, [System.Text.Encoding]::UTF8)
    } else {
        $existingLines = @("# Generated by init_setup.ps1 ($(Get-Date -Format 'yyyy-MM-dd HH:mm:ss'))")
    }

    $seen = @{}
    $outLines = [System.Collections.Generic.List[string]]::new()
    foreach ($rawLine in $existingLines) {
        $trimmed = $rawLine.TrimStart([char]0xfeff).Trim()
        if ($trimmed -and -not $trimmed.StartsWith("#")) {
            $idx = $trimmed.IndexOf("=")
            if ($idx -gt 0) {
                $k = $trimmed.Substring(0, $idx).Trim()
                if ($Updates.Contains($k)) {
                    if (-not $seen.ContainsKey($k)) {
                        $outLines.Add("$k=$($Updates[$k])")
                        $seen[$k] = $true
                    }
                    continue
                }
            }
        }
        $outLines.Add($rawLine)
    }

    foreach ($k in $Updates.Keys) {
        if (-not $seen.ContainsKey($k)) {
            $outLines.Add("$k=$($Updates[$k])")
            $seen[$k] = $true
        }
    }

    [System.IO.File]::WriteAllLines($Path, $outLines, [System.Text.UTF8Encoding]::new($false))
}

function Get-DetectedObsidianVaults {
    param([string]$ConfigPath = (Join-Path $env:APPDATA "obsidian\obsidian.json"))
    $vaults = @()
    if (-not $ConfigPath -or -not (Test-Path $ConfigPath)) { return $vaults }
    try {
        $raw = [System.IO.File]::ReadAllText($ConfigPath, [System.Text.Encoding]::UTF8)
        $json = $raw | ConvertFrom-Json
        if ($json -and $json.vaults) {
            foreach ($prop in $json.vaults.PSObject.Properties) {
                $p = [string]($prop.Value.path)
                if ($p -and $p.Trim()) {
                    $vaults += $p.Trim()
                }
            }
        }
    } catch {}
    return ($vaults | Select-Object -Unique)
}

